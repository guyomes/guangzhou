export type CityId = 'guangzhou' | 'shenzhen' | 'shantou' | 'chaozhou';

export interface CityInfo {
  id: CityId;
  nameFr: string;
  nameCn: string;
  pinyin: string;
  taglineFr: string;
  centerLat: number;
  centerLng: number;
  zoomLevel: number;
  image: string;
}

export type AttractionCategory = 
  | 'heritage'
  | 'modern'
  | 'food'
  | 'nature'
  | 'art_hidden'
  | 'mall'
  | 'restaurant'
  | 'event'
  | 'hotel';

export interface ReviewScore {
  source: 'dianping' | 'tripadvisor' | 'google' | 'ctrip' | 'xiaohongshu';
  sourceName: string;
  sourceType: 'chinese' | 'western';
  score: number; // 0 to 5.0
  reviewCount: number;
  badge?: string; // e.g. "必吃榜" or "Choix des Voyageurs"
  highlightQuote: string;
  url?: string;
}

export interface Attraction {
  id: string;
  cityId: CityId;
  nameFr: string;
  nameEn: string;
  nameCn: string;
  pinyin: string;
  cantonesePhonetic: string;
  category: AttractionCategory;
  district: string;
  lat: number;
  lng: number;
  metroInfoFr: string;
  metroInfoEn: string;
  addressCn: string;
  image: string;
  thumbnailAlt: string;
  descriptionFr: string;
  descriptionEn: string;
  culturalNoteFr: string;
  visitingTipsFr: string[];
  recommendedDuration: string; // e.g. "1h30 - 2h"
  estimatedCostRmb: number; // 0 for free
  bestTime: string; // e.g. "Coucher de soleil & Nuit"
  overallScore: number; // e.g. 4.8 / 5
  ourOpinionFr: string; // "Notre avis : ..."
  annualVisitors: number; // e.g. 2500000
  tripadvisorUrl: string;
  bookingUrl?: string;
  wikipediaUrl?: string;
  // Wikipedia metadata generated by scripts/fetch_wikipedia_links.py.
  // All fields are optional and null when no article could be resolved.
  fr_title?: string | null; // Canonical French Wikipedia article title
  fr_url?: string | null; // https://fr.wikipedia.org/wiki/...
  zh_title?: string | null; // Canonical Chinese Wikipedia article title
  zh_url?: string | null; // Google-Translate proxy link to the zh article
  en_title?: string | null; // English title (intermediate lookup result)
  wikidata?: string | null; // Wikidata QID, e.g. "Q16572"
  fr_verdict?: string | null; // city | guangdong | other_china | unknown | foreign
  zh_verdict?: string | null; // city | guangdong | other_china | unknown | foreign
  fr_via?: string | null; // hint | search | sitelink | district_page
  zh_via?: string | null; // hint | search | sitelink | district_page
  scores?: ReviewScore[];
  isTopRated: boolean;
  isHiddenGem: boolean;
  tags: string[];
}

export interface ItineraryStop {
  attractionId: string;
  timeSlot: 'matin' | 'dejeuner' | 'apres-midi' | 'soiree';
  durationHours: number;
  activityFr: string;
  foodSuggestionFr?: string;
  transportAdviceFr: string;
}

export interface ItineraryDay {
  dayNumber: number;
  titleFr: string;
  themeFr: string;
  summaryFr: string;
  stops: ItineraryStop[];
}

export interface SuggestedItinerary {
  id: string;
  cityId: CityId | 'multi';
  durationDays: number;
  titleFr: string;
  subtitleFr: string;
  pace: 'relaxed' | 'balanced' | 'packed';
  focus: 'all' | 'food' | 'heritage' | 'modern' | 'hidden';
  days: ItineraryDay[];
}

export interface UserTripPlan {
  durationDays: number;
  selectedAttractionIds: string[];
  customDays: { [day: number]: string[] };
}
